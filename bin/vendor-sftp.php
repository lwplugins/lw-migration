/**
 * Copies, prefixes and describes the subset.
 *
 * @param array<int, string> $args Command line: script, phpseclib dir, constant_time_encoding dir, target dir.
 * @return int Exit code.
 */
function main( array $args ): int {
	[ , $seclib, $cte, $target ] = $args + [ '', '', '', '' ];
	$target                      = rtrim( (string) $target, '/' );
	foreach ( [ $seclib . '/phpseclib/Net/SFTP.php', $cte . '/src/Base64.php' ] as $must ) {
		if ( ! is_file( $must ) ) {
			fwrite( STDERR, 'Missing ' . $must . "\n" );
			return 1;
		}
	}
	$files = [];
	foreach ( PHPSECLIB_KEEP as $keep ) {
		foreach ( expand( $seclib . '/phpseclib/', $keep ) as $relative ) {
			$files[ $seclib . '/phpseclib/' . $relative ] = 'phpseclib3/' . $relative;
		}
	}
	foreach ( CTE_KEEP as $keep ) {
		$files[ $cte . '/src/' . $keep ] = 'ParagonIE/ConstantTime/' . $keep;
	}
	$bytes = 0;
	foreach ( $files as $from => $to ) {
		$code = rewrite( (string) file_get_contents( $from ) );
		$path = $target . '/' . $to;
		if ( ! is_dir( dirname( $path ) ) ) {
			mkdir( dirname( $path ), 0755, true );
		}
		file_put_contents( $path, $code );
		$bytes += strlen( $code );
	}
	copy( $seclib . '/LICENSE', $target . '/phpseclib3/LICENSE' );
	copy( $cte . '/LICENSE.txt', $target . '/ParagonIE/ConstantTime/LICENSE.txt' );
	file_put_contents(
		$target . '/SOURCE.txt',
		"Generated by bin/vendor-sftp.sh - do not edit by hand.\n"
		. "phpseclib/phpseclib 3.0.57 (MIT), tag commit d17e0ddaeaf6f22f7e007cbb437d78792fe2a0e4, subset for SFTP.\n"
		. "paragonie/constant_time_encoding 3.1.3 (MIT), tag v3.1.3 commit d5b01a39b3415c2cd581d3bd3a3575c1ebbd8e77, 5 classes.\n"
		. 'Namespaces prefixed with ' . PREFIX . "\n"
		. sprintf( "%d PHP files, %d bytes.\n", count( $files ), $bytes )
	);
	fwrite( STDOUT, sprintf( "%d files, %d bytes\n", count( $files ), $bytes ) );

	return 0;
}

/**
 * @param string $root Source root ending in a slash.
 * @param string $keep A file, or a folder ending in a slash.
 * @return array<int, string> PHP files relative to $root.
 */
function expand( string $root, string $keep ): array {
	if ( ! str_ends_with( $keep, '/' ) ) {
		return [ $keep ];
	}
	$out = [];
	$it  = new \RecursiveIteratorIterator( new \RecursiveDirectoryIterator( $root . $keep, \FilesystemIterator::SKIP_DOTS ) );
	foreach ( $it as $file ) {
		if ( 'php' === $file->getExtension() ) {
			$out[] = substr( $file->getPathname(), strlen( $root ) );
		}
	}
	sort( $out );

	return $out;
}

/**
 * Prefixes every phpseclib3\ and ParagonIE\ConstantTime\ name: namespace and
 * use statements, fully qualified names, and class names inside string
 * literals (phpseclib builds engine, format and curve class names from
 * strings). Adds the ABSPATH guard after the namespace statement, and
 * moves the comments before it (the license docblock) below the guard, so
 * the guard is near the top of the file where checks look for it.
 *
 * @param string $code PHP source.
 * @return string The prefixed source.
 */
function rewrite( string $code ): string {
	$out       = '';
	$tokens    = token_get_all( $code );
	$guard     = false;
	$named     = false;
	$moved     = '';
	$skipSpace = false;
	foreach ( $tokens as $token ) {
		if ( ! is_array( $token ) ) {
			$out .= $token;
			if ( ';' === $token && $guard ) {
				$out  .= "\n\ndefined( 'ABSPATH' ) || exit;" . ( '' === $moved ? '' : "\n\n" . rtrim( $moved ) );
				$guard = false;
			}
			continue;
		}
		[ $id, $text ] = $token;
		if ( ! $named && in_array( $id, [ T_DOC_COMMENT, T_COMMENT ], true ) ) {
			$moved    .= $text . "\n";
			$skipSpace = true;
			continue;
		}
		if ( $skipSpace && T_WHITESPACE === $id ) {
			$skipSpace = false;
			continue;
		}
		$skipSpace = false;
		if ( T_NAMESPACE === $id ) {
			$guard = true;
			$named = true;
		}
		if ( in_array( $id, [ T_NAME_QUALIFIED, T_NAME_FULLY_QUALIFIED ], true ) ) {
			$text = (string) preg_replace( '/^(\\\\?)(phpseclib3\\\\|ParagonIE\\\\ConstantTime\\\\)/', '$1' . addcslashes( PREFIX, '\\' ) . '$2', $text );
			$text = (string) preg_replace( '/^(\\\\?)(phpseclib3|ParagonIE\\\\ConstantTime)$/', '$1' . addcslashes( PREFIX, '\\' ) . '$2', $text );
		}
		if ( in_array( $id, [ T_CONSTANT_ENCAPSED_STRING, T_ENCAPSED_AND_WHITESPACE ], true ) ) {
			$text = (string) preg_replace_callback(
				'/(\\\\{0,2})(phpseclib3|ParagonIE)(\\\\{1,2})/',
				static function ( array $m ): string {
					$sep = $m[3];
					return $m[1] . str_replace( '\\', $sep, PREFIX ) . $m[2] . $m[3];
				},
				$text
			);
		}
		$out .= $text;
	}
	return $out;
}

exit( (int) main( $argv ) );
